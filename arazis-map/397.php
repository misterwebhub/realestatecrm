        'blacklist':'#212529',
        'hold':'#A0522D',
        'registry':'#E53935',
        'issue':'#6C757D'
    };

    const plots = <?php echo json_encode($plots, JSON_UNESCAPED_SLASHES|JSON_UNESCAPED_UNICODE); ?> || [];
    console.log('arazi plots payload:', plots);

    // Simple number-based lookup: map plot_number (digits only) -> status
    const plotStatusByNumber = {};
    plots.forEach(p => {
        const numMatch = String(p.plot_number || p.id || '').match(/\d+/);
        if (numMatch) plotStatusByNumber[numMatch[0]] = p.status || 'available';
    });
    console.log('plotStatusByNumber keys:', Object.keys(plotStatusByNumber));

    // If DB uses a different numeric range (e.g. DB: 55..77, map tiles: 1..23)
    // detect contiguous numeric range and compute an offset to map tile numbers
    let detectedOffset = null;
    const numericKeys = Object.keys(plotStatusByNumber).map(k => parseInt(k, 10)).filter(n => !isNaN(n)).sort((a,b) => a - b);
    if (numericKeys.length) {
        const minK = numericKeys[0];
        const maxK = numericKeys[numericKeys.length - 1];
        if ((maxK - minK + 1) === numericKeys.length && minK > 1) {
            detectedOffset = minK - 1; // tileNumber + offset === dbPlotNumber
            console.log('detected plot_number offset:', detectedOffset);
        }
    }

    function mapTileNumberToPlotNumber(tileNumStr) {
        if (!tileNumStr) return tileNumStr;
        if (plotStatusByNumber[tileNumStr]) return tileNumStr;
        if (detectedOffset !== null) {
            const candidate = String((parseInt(tileNumStr, 10) || 0) + detectedOffset);
            if (plotStatusByNumber[candidate]) return candidate;
        }
        return tileNumStr;
    }

    // For each tile element: extract digits from visible text and color by status
    const candidates = Array.from(document.querySelectorAll('div[id^="p"]'));
    candidates.forEach(function(el){
        const text = (el.textContent || '').trim();
        const numeric = (text.match(/\d+/) || [])[0] || (el.id || '').replace(/^p/, '');
        const mapped = mapTileNumberToPlotNumber(numeric);
        const status = mapped && plotStatusByNumber[mapped] ? plotStatusByNumber[mapped] : 'available';
        el.style.backgroundImage = 'none';
        const clr = colorMap[status] || colorMap['available'];
        el.style.backgroundColor = clr;
        el.style.color = (['#212529', '#28A745', '#E53935', '#A0522D'].includes(clr)) ? '#fff' : '#000';
        console.log('tile mapping:', el.id, {text: text, numeric: numeric, mapped: mapped, status: plotStatusByNumber[mapped], color: clr});
        if (!plotStatusByNumber[mapped]) console.log('tile NOT matched (defaulted available):', el.id, {text: text, numeric: numeric, mapped: mapped});
    });

    // Any map tiles that weren't matched should be shown as Available (yellow)
    const allTiles = Array.from(document.querySelectorAll('div[id^="p"]'));
    allTiles.forEach(function(el){
        const compBg = getComputedStyle(el).backgroundColor;
        const isTransparent = !compBg || compBg === 'transparent' || compBg === 'rgba(0, 0, 0, 0)';
        if (isTransparent) {
            el.style.backgroundImage = 'none';
            el.style.backgroundColor = colorMap['available'];
            el.style.color = '#000';
        }
    });
});

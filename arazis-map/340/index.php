    function getTileKey(el) {
        let key = (el.id || '').replace(/^p/i, '').trim().toUpperCase();
        if (key) return key;

        const text = (el.textContent || '').trim();
        const full = text.match(/^[0-9]+[A-Z]?$/i);
        if (full) return full[0].toUpperCase();

        return (text.match(/\d+/) || [])[0] || '';
    }

    const candidates = Array.from(document.querySelectorAll('div[id^="p"]'));
    candidates.forEach(function(el){
        const tileKey = getTileKey(el);
        const status = plotStatusByNumber[tileKey] || 'available';
        
        el.style.backgroundImage = 'none';
        const clr = colorMap[status] || colorMap['available'];
        el.style.backgroundColor = clr;

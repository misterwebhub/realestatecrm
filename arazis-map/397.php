// Server-side: query DB directly for plots of this arazi (35) and compute statuses
// Load DB credentials from .env
function env_val($key, $default = null) {
    // Prefer actual environment variables (e.g., set in Apache/nginx or system)
    $val = getenv($key);
    if ($val !== false && $val !== null && $val !== '') return $val;

    // Fallback to reading .env file in project root (for local setups)
    $envPath = __DIR__ . '/../.env';
    $env = @file_get_contents($envPath);
    if (! $env) return $default;
    if (preg_match('/^' . preg_quote($key, '/') . '=(.*)$/m', $env, $m)) {
        return trim(trim($m[1]), "\"'");
    }
    return $default;
}

// Prefer values from the project's .env file first (legacy maps use project config).
function read_dotenv_file($path) {
    $pairs = [];
    $content = @file_get_contents($path);
    if (! $content) return $pairs;
    foreach (preg_split("/\r?\n/", $content) as $line) {
        $line = trim($line);
        if ($line === '' || strpos($line, '#') === 0) continue;
        if (!strpos($line, '=')) continue;
        list($k,$v) = explode('=', $line, 2);
        $k = trim($k);
        $v = trim($v);
        $v = trim($v, "\"'");
        $pairs[$k] = $v;
    }
    return $pairs;
}


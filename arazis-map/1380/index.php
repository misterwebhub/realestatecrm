                }
            }
        }

        // 'issue' status removed — never force a plot to 'issue'. Explicit DB
        // statuses (hold, booked, registry, etc.) resolved above are preserved.
        if ($status === null || $status === 'issue') $status = 'available';

        $plots[] = [
            'id' => $plotId,
            'plot_number' => $r['plot_number'],
            'title' => $r['title'] ?? null,
            'status' => $status,
            'area' => $r['area'],
        ];

window.plots = <?php echo json_encode($plots, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE); ?> || [];

document.addEventListener('DOMContentLoaded', function(){
    const colorMap = {
        'available': '#FFC107',
        'booked': '#28A745',
        'booked_advance': '#28A745',
        'booked-advance': '#28A745',
        'not_for_sale': '#9E9E9E',
        'not-for-sale': '#9E9E9E',
        'blacklist': '#212529',
        'hold': '#A0522D',
        'registry': '#E53935',
        'issue': '#FFC107'
    };

    const statusMap = {};
    window.plots.forEach(p => {
        const plotTitle = String(p.title || '').trim();
        if (plotTitle) {
            statusMap[plotTitle] = String(p.status).toLowerCase().replace(/_/g, '-');
        }
    });

    console.log('Loaded Plots:', window.plots.length);
    console.log('Status Map:', statusMap);

    // Apply colors to all markers
    document.querySelectorAll('.marker').forEach(marker => {
        const span = marker.querySelector('span');
        if (!span) return;
       
        const plotNum = span.textContent.trim();
        if (!plotNum) return;

        const status = statusMap[plotNum] || 'available';
        const color = colorMap[status] || '#FFC107';
        
        marker.style.backgroundColor = color;
        marker.style.color = (['#212529','#28A745','#E53935','#A0522D'].includes(color)) ? '#fff' : '#000';
    });
});
